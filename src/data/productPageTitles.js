export function getProductPageTitle(product, lang = "ar") {
  const language = lang === "fr" ? "fr" : "ar";
  const title = PRODUCT_TITLES_BY_ID[product?.id]
    || PRODUCT_TITLES_BY_REFERENCE[String(product?.reference || "").trim()];

  if (title?.[language]) return title[language];

  const reference = String(product?.reference || product?.id || "").trim();
  return language === "fr"
    ? `Chaussure femme en gros — modèle ${reference}`
    : `حذاء نسائي بالجملة — موديل ${reference}`;
}

