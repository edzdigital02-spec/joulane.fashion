const PAIRS_PER_CARTON = 18;
const DEFAULT_UNIT_PRICE = 3200;
const SHOE_SIZES = Object.freeze([36, 37, 38, 39, 40, 41]);

function normalizeShoeSizeFeature(feature) {
  return String(feature).replace(/35([^0-9]*?)44/g, (_, separator) => `36${separator}41`);
}

export const PRODUCTS = PRODUCT_DATA.map(product => {
  const configuredPairs = Number(product.pairsPerSeries);
  const pairsPerSeries = Number.isFinite(configuredPairs) && configuredPairs >= 1
    ? Math.floor(configuredPairs)
    : PAIRS_PER_CARTON;
  const unitPrice = Number(product.price) > 0 ? Number(product.price) : DEFAULT_UNIT_PRICE;
  const cartonPrice = Number(product.seriesPrice) > 0
    ? Number(product.seriesPrice)
    : unitPrice * pairsPerSeries;

  return {
    ...product,
    price: unitPrice,
    seriesPrice: cartonPrice,
    pairsPerSeries,
    sizes: [...SHOE_SIZES],
    features: {
      ar: (product.features?.ar || []).map(feature => normalizeShoeSizeFeature(feature).replace(/\b15\b/g, String(pairsPerSeries))),
      fr: (product.features?.fr || []).map(feature => normalizeShoeSizeFeature(feature).replace(/\b15\b/g, String(pairsPerSeries)))
    }
  };
});
